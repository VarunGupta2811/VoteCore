-- ============================================================
-- 1. AUTHENTICATION & IDENTITY MODULE
-- ============================================================

CREATE TABLE UACCOUNT (
    PID NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    FIRST_NAME VARCHAR2(80) NOT NULL,
    LAST_NAME VARCHAR2(80) NOT NULL,
    MOBILE VARCHAR2(15) NOT NULL UNIQUE,
    EMAIL VARCHAR2(254) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    COUNTRY VARCHAR2(80) DEFAULT 'India',
    STATE VARCHAR2(80),
    IS_ACTIVE NUMBER(1) DEFAULT 1,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE GOV_IDENTITY (
    PID NUMBER(19) PRIMARY KEY,
    EPIC_ID VARCHAR2(255) UNIQUE,
    AADHAAR_NO VARCHAR2(255) UNIQUE,
    FULL_NAME VARCHAR2(160),
    DOB DATE,
    IS_VERIFIED NUMBER(1) DEFAULT 0,
    CONSTRAINT FK_GOV_USER FOREIGN KEY (PID) REFERENCES UACCOUNT(PID)
);

CREATE TABLE IDENTITY_WALLET (
    WALLET_ID NUMBER(10) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PID NUMBER(19) NOT NULL,
    IDENTITY_TYPE VARCHAR2(50) DEFAULT 'GOV',
    EPIC_ID VARCHAR2(255),
    ADDED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_WALLET_USER FOREIGN KEY (PID) REFERENCES UACCOUNT(PID)
);

CREATE TABLE OTP_VERIFICATION (
    OTP_ID NUMBER(10) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PID NUMBER(19) NOT NULL,
    OTP_CODE VARCHAR2(10),
    OTP_CODE_HASH VARCHAR2(255),
    EXPIRES_AT TIMESTAMP NOT NULL,
    VERIFIED NUMBER(1) DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_OTP_USER FOREIGN KEY (PID) REFERENCES UACCOUNT(PID)
);

CREATE TABLE USER_SESSIONS (
    SESSION_ID VARCHAR2(64) PRIMARY KEY,
    PID NUMBER(19) NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_SESSION_USER FOREIGN KEY (PID) REFERENCES UACCOUNT(PID)
);


