CREATE TABLE ELECTION_PARTY_MEMBER (
    ELECTION_PARTY_ID NUMBER(10) NOT NULL,
    ELECTION_ID NUMBER(10) NOT NULL,
    PID NUMBER(19) NOT NULL,
