-- ============================================================
-- 8. LIVE RESULT VIEW (Optimized with NVL for Independents)
-- ============================================================

CREATE OR REPLACE VIEW V_ELECTION_RESULT_BY_POST AS
SELECT
    E.ELECTION_ID,
    E.TITLE AS ELECTION_TITLE,
    POS.POSITION_ID,
    POS.TITLE AS POSITION_TITLE,
    C.CANDIDATE_ID,
    C.PID AS CANDIDATE_PID,
    U.FIRST_NAME || ' ' || U.LAST_NAME AS CANDIDATE_NAME,
    EP.ELECTION_PARTY_ID,
    NVL(PP.NAME, 'Independent') AS PARTY_NAME,
    COUNT(V.VOTE_ID) AS TOTAL_VOTES
FROM ELECTION E
JOIN ELECTION_POSITION POS
    ON POS.ELECTION_ID = E.ELECTION_ID
JOIN CANDIDATE C
    ON C.ELECTION_ID = POS.ELECTION_ID
   AND C.POSITION_ID = POS.POSITION_ID
JOIN UACCOUNT U
    ON U.PID = C.PID
LEFT JOIN ELECTION_PARTY EP
    ON EP.ELECTION_PARTY_ID = C.ELECTION_PARTY_ID
LEFT JOIN POLITICAL_PARTY PP
    ON PP.PARTY_ID = EP.PARTY_ID
LEFT JOIN VOTE V
    ON V.ELECTION_ID = C.ELECTION_ID
   AND V.POSITION_ID = C.POSITION_ID
   AND V.CANDIDATE_ID = C.CANDIDATE_ID
GROUP BY
    E.ELECTION_ID, E.TITLE, POS.POSITION_ID, POS.TITLE,
    C.CANDIDATE_ID, C.PID, U.FIRST_NAME, U.LAST_NAME,
    EP.ELECTION_PARTY_ID, PP.NAME;


-- ============================================================
-- 9. INTEGRITY AND AUDIT TRIGGERS
-- ============================================================

CREATE OR REPLACE TRIGGER TRG_CAND_NEUTRALITY
BEFORE INSERT OR UPDATE OF ELECTION_ID, PID ON CANDIDATE
FOR EACH ROW
DECLARE
    V_ORGANIZER_PID ELECTION.ORGANIZER_PID%TYPE;
BEGIN
    SELECT ORGANIZER_PID INTO V_ORGANIZER_PID
    FROM ELECTION
    WHERE ELECTION_ID = :NEW.ELECTION_ID;

    IF V_ORGANIZER_PID = :NEW.PID THEN
        RAISE_APPLICATION_ERROR(-20001, 'The election organizer cannot be a candidate in the same election.');
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_EPARTY_NEUTRALITY
BEFORE INSERT OR UPDATE OF ELECTION_ID, CAMPAIGN_LEADER_PID ON ELECTION_PARTY
FOR EACH ROW
DECLARE
    V_ORGANIZER_PID ELECTION.ORGANIZER_PID%TYPE;
BEGIN
    SELECT ORGANIZER_PID INTO V_ORGANIZER_PID
    FROM ELECTION
    WHERE ELECTION_ID = :NEW.ELECTION_ID;

    IF V_ORGANIZER_PID = :NEW.CAMPAIGN_LEADER_PID THEN
        RAISE_APPLICATION_ERROR(-20002, 'The election organizer cannot lead a party in the same election.');
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_EPM_NEUTRALITY
BEFORE INSERT OR UPDATE OF ELECTION_ID, PID ON ELECTION_PARTY_MEMBER
FOR EACH ROW
DECLARE
    V_ORGANIZER_PID ELECTION.ORGANIZER_PID%TYPE;
BEGIN
    SELECT ORGANIZER_PID INTO V_ORGANIZER_PID
    FROM ELECTION
    WHERE ELECTION_ID = :NEW.ELECTION_ID;

    IF V_ORGANIZER_PID = :NEW.PID THEN
        RAISE_APPLICATION_ERROR(-20003, 'The election organizer cannot join a party in the same election.');
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_AUDIT_USER
AFTER INSERT OR UPDATE ON UACCOUNT
FOR EACH ROW
DECLARE
    V_PID UACCOUNT.PID%TYPE;
BEGIN
    V_PID := :NEW.PID;
    INSERT INTO AUDIT_LOGS (PID, ACTION_TYPE, ACTION_TIME, DETAILS)
    VALUES (
        V_PID,
        'UACCOUNT_' || ORA_SYSEVENT,
        SYSTIMESTAMP,
        'User record changed by database trigger.'
    );
END;
/

CREATE OR REPLACE TRIGGER TRG_AUDIT_ELECTION
AFTER INSERT OR UPDATE OR DELETE ON ELECTION
FOR EACH ROW
DECLARE
    V_PID UACCOUNT.PID%TYPE;
    V_ELECTION_ID ELECTION.ELECTION_ID%TYPE;
BEGIN
    IF DELETING THEN
        V_PID := COALESCE(:OLD.ORGANIZER_APPOINTED_BY, :OLD.ORGANIZER_PID);
        V_ELECTION_ID := :OLD.ELECTION_ID;
    ELSE
        V_PID := COALESCE(:NEW.ORGANIZER_APPOINTED_BY, :NEW.ORGANIZER_PID);
        V_ELECTION_ID := :NEW.ELECTION_ID;
    END IF;

    IF V_PID IS NOT NULL THEN
        INSERT INTO AUDIT_LOGS (PID, ACTION_TYPE, ACTION_TIME, DETAILS)
        VALUES (
            V_PID,
            'ELECTION_' || ORA_SYSEVENT,
            SYSTIMESTAMP,
            'Election ' || TO_CHAR(V_ELECTION_ID) || ' record changed by database trigger.'
        );
    END IF;
END;
