CREATE TABLE CANDIDATE (
    CANDIDATE_ID NUMBER(10) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ELECTION_ID NUMBER(10) NOT NULL,
    PID NUMBER(19) NOT NULL,
    POSITION VARCHAR2(100) NOT NULL,
    POSITION_ID NUMBER(10) NOT NULL,
    ELECTION_PARTY_ID NUMBER(10),  -- NULL allows for Independent Candidates
    MANIFESTO VARCHAR2(2000),
    STATUS VARCHAR2(20) DEFAULT 'PENDING' CHECK (STATUS IN ('PENDING', 'ACTIVE', 'REJECTED', 'WITHDRAWN')),
    ORGANIZER_APPROVED_AT TIMESTAMP,
    ORGANIZER_APPROVED_BY NUMBER(19),
    CONSTRAINT FK_CAND_ELECTION FOREIGN KEY (ELECTION_ID) REFERENCES ELECTION(ELECTION_ID),
    CONSTRAINT FK_CAND_USER FOREIGN KEY (PID) REFERENCES UACCOUNT(PID),
    CONSTRAINT FK_CAND_POS FOREIGN KEY (POSITION_ID) REFERENCES ELECTION_POSITION(POSITION_ID),
    CONSTRAINT FK_CAND_PARTY FOREIGN KEY (ELECTION_PARTY_ID) REFERENCES ELECTION_PARTY(ELECTION_PARTY_ID),
    CONSTRAINT UQ_CAND_ELECTION UNIQUE (ELECTION_ID, PID, POSITION_ID)
