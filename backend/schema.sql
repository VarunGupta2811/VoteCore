    STATUS VARCHAR2(20) DEFAULT 'PENDING',
    JOINED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    PRIMARY KEY (ELECTION_PARTY_ID, PID),
    CONSTRAINT FK_EPM_PARTY FOREIGN KEY (ELECTION_PARTY_ID) REFERENCES ELECTION_PARTY(ELECTION_PARTY_ID),
    CONSTRAINT FK_EPM_ELECTION FOREIGN KEY (ELECTION_ID) REFERENCES ELECTION(ELECTION_ID),
    CONSTRAINT FK_EPM_USER FOREIGN KEY (PID) REFERENCES UACCOUNT(PID)
