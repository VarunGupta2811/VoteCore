-- ============================================================
-- 3. CORE ELECTION MODULE
-- ============================================================

CREATE TABLE ELECTION (
    ELECTION_ID NUMBER(10) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    JURISDICTION_ID VARCHAR2(40) NOT NULL,
    TITLE VARCHAR2(160) NOT NULL,
    DESCRIPTION VARCHAR2(2000),
    STATUS VARCHAR2(20) DEFAULT 'UPCOMING' CHECK (STATUS IN ('UPCOMING', 'NOMINATION', 'ACTIVE', 'COMPLETED', 'ARCHIVED')),
    START_DATE TIMESTAMP NOT NULL,
    END_DATE TIMESTAMP NOT NULL,
    ORGANIZER_PID NUMBER(19),
    ORGANIZER_APPOINTED_AT TIMESTAMP,
    ORGANIZER_APPOINTED_BY NUMBER(19),
    CONSTRAINT FK_ELECTION_HOST FOREIGN KEY (JURISDICTION_ID) REFERENCES HOST_JURISDICTION(JURISDICTION_ID),
    CONSTRAINT FK_ELECTION_ORG FOREIGN KEY (ORGANIZER_PID) REFERENCES UACCOUNT(PID)
);

CREATE TABLE ELECTION_POSITION (
    POSITION_ID NUMBER(10) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ELECTION_ID NUMBER(10) NOT NULL,
    TITLE VARCHAR2(100) NOT NULL,
    DISPLAY_ORDER NUMBER(5) DEFAULT 0,
    STATUS VARCHAR2(20) DEFAULT 'OPEN',
    CONSTRAINT FK_POS_ELECTION FOREIGN KEY (ELECTION_ID) REFERENCES ELECTION(ELECTION_ID)
);

CREATE TABLE EVENT_PARTICIPANTS (
    ELECTION_ID NUMBER(10) NOT NULL,
    PID NUMBER(19) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'PENDING' CHECK (STATUS IN ('PENDING', 'ELIGIBLE', 'REJECTED')),
    REGISTERED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    PRIMARY KEY (ELECTION_ID, PID),
    CONSTRAINT FK_EP_ELEC FOREIGN KEY (ELECTION_ID) REFERENCES ELECTION(ELECTION_ID),
    CONSTRAINT FK_EP_USR FOREIGN KEY (PID) REFERENCES UACCOUNT(PID)
);


-- ============================================================
-- 4. NOMINATIONS & CAMPAIGN MODULE
-- ============================================================

